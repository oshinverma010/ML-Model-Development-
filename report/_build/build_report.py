"""Build report/report_content.md from report/_build/sections/*.md and results/*.csv.

Template syntax (in sections/*.md)
  {{key|fmt}}              a number or string from results (see keys() below; dump them with --keys)
  {{table:name}}           a Markdown table generated by tables.py from results/*.csv
  {{code:path:Name}}       real source code of a function/class (via ast), as a fenced block labelled "# from path"
  {{refs}}                 verified references from results/reference_check.csv
Formats: 0/1/2/3/4 decimals, i (integer with thousands separator), p0/p1 (x100 and %), sci (2-digit scientific),
         s (string, default for non-numeric values).
Any unknown key is an error, so the text cannot drift from the code: a number that is not in a results file cannot appear.

Run:  python report/_build/build_report.py            (writes report/report_content.md and prints the word count)
      python report/_build/build_report.py --keys     (lists every available key)
"""
