def slug(x) -> str:
    return re.sub(r"[^a-z0-9]+", "_", str(x).lower()).strip("_")


def flat(V: dict, df: pd.DataFrame, prefix: str, keys: list[str]) -> None:
    """Register every cell of df as V[prefix_<key values>_<column>]."""
    for _, r in df.iterrows():
        k = "_".join(slug(r[c]) for c in keys)
        for c in df.columns:
            if c in keys:
                continue
            V[f"{prefix}_{k}_{slug(c)}" if k else f"{prefix}_{slug(c)}"] = r[c]


def read(name: str) -> pd.DataFrame | None:
    p = RES / name
    return pd.read_csv(p).drop_duplicates().reset_index(drop=True) if p.exists() else None


