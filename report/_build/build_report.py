# --------------------------------------------------------------------------- rendering
def fmt(v, spec: str | None) -> str:
    if spec in (None, "", "s"):
        if isinstance(v, (float, np.floating)):
            raise ValueError("float needs a format spec")
        return str(v)
    if isinstance(v, str):
        raise ValueError(f"string value with numeric format {spec}: {v}")
    v = float(v)
    if np.isnan(v):
        return "n/a"
    if spec == "i":
        return f"{int(round(v)):,}"
    if spec.startswith("p"):
        return f"{100 * v:.{int(spec[1:])}f}%"
    if spec == "sci":
        return f"{v:.1e}"
    if spec.isdigit():
        return f"{v:.{int(spec)}f}"
    raise ValueError(spec)


def code_block(path: str, name: str) -> str:
    src = (ROOT / path).read_text(encoding="utf-8")
    tree = ast.parse(src)
    lines = src.splitlines()
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name == name:
            start = (node.decorator_list[0].lineno if node.decorator_list else node.lineno) - 1
            body = lines[start:node.end_lineno]
            return f"```python\n# from {path}\n" + "\n".join(body) + "\n```"
    raise KeyError(f"{name} not found in {path}")


def render(text: str, V: dict) -> str:
    import tables as T  # noqa: WPS433

    def sub(m: re.Match) -> str:
        inner = m.group(1).strip()
        if inner.startswith("table:"):
            return T.make(inner[6:], V)
        if inner.startswith("code:"):
            _, path, name = inner.split(":", 2)
            return code_block(path, name)
        if inner == "refs":
            return T.references()
        key, _, spec = inner.partition("|")
        if key not in V:
            raise KeyError(f"unknown key: {key}")
        return fmt(V[key], spec)

    return re.sub(r"\{\{(.+?)\}\}", sub, text)


def body_word_count(md: str) -> int:
    """Words of body prose: excludes code blocks, tables, figures, headings, references and appendices."""
    md = md.split("\n## Appendices")[0] if "\n## Appendices" in md else md
    md = md.split("\n## 13.")[0]
    md = re.sub(r"```.*?```", "", md, flags=re.S)
    keep = []
    for ln in md.splitlines():
        s = ln.strip()
        if not s or s.startswith(("|", "#", "![", "---", "*Week 3")):
            continue
        keep.append(s)
    text = re.sub(r"[`*_]", "", " ".join(keep))
    return len(re.findall(r"[A-Za-z0-9][A-Za-z0-9.,%'/+=\-<>≤≥]*", text))


def main() -> None:
    V = keys()
    if "--keys" in sys.argv:
        for k in sorted(V):
            print(k, "=", V[k])
        return
    parts = [render(p.read_text(encoding="utf-8"), V) for p in sorted(SECTIONS.glob("*.md"))]
    md = "\n\n".join(s.strip("\n") for s in parts) + "\n"
    md = md.replace("\r\n", "\n")
    OUT.write_text(md, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}; body prose words: {body_word_count(md):,}; total characters {len(md):,}")


if __name__ == "__main__":
    main()
